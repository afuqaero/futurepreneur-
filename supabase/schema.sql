-- futurePreneur PostgreSQL schema for Supabase.
-- Run this in Supabase SQL Editor before deploying the Vercel app.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  role text not null default 'learner' check (role in ('learner', 'admin')),
  business_name text not null default '',
  sector text not null default '',
  customer_type text not null default '',
  stage text not null default '',
  team_size text not null default '',
  revenue_band text not null default '',
  years text not null default '',
  main_challenge text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.modules (
  id text primary key,
  component text not null,
  title text not null,
  tagline text not null default '',
  level text not null default 'Foundation',
  hours integer not null default 1,
  outcome text not null default '',
  intro jsonb not null default '{}'::jsonb,
  practical jsonb not null default '{}'::jsonb,
  status text not null default 'draft' check (status in ('draft', 'published')),
  position integer not null default 0,
  version integer not null default 1,
  updated_at timestamptz not null default now()
);

create table if not exists public.lessons (
  id text primary key,
  module_id text not null references public.modules(id) on delete cascade,
  position integer not null default 0,
  title text not null,
  minutes integer not null default 10,
  summary text not null default '',
  body jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.questions (
  id text primary key,
  module_id text references public.modules(id) on delete cascade,
  component text,
  kind text not null check (kind in ('diagnostic', 'quiz', 'scenario')),
  topic text not null default '',
  prompt text not null,
  options jsonb not null default '[]'::jsonb,
  correct integer not null default 0,
  explanation text not null default '',
  active boolean not null default true,
  position integer not null default 0
);

create table if not exists public.diagnostic_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  answers jsonb not null default '{}'::jsonb,
  component_scores jsonb not null default '{}'::jsonb,
  overall integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.lesson_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id text not null references public.lessons(id) on delete cascade,
  completed_at timestamptz not null default now(),
  primary key (user_id, lesson_id)
);

create table if not exists public.attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null,
  module_id text references public.modules(id) on delete cascade,
  component text not null default '',
  score integer not null default 0,
  passed boolean not null default false,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.plan_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  detail text not null default '',
  due date,
  done boolean not null default false,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.coach_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mode text not null default 'teach',
  title text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.coach_messages (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.coach_sessions(id) on delete cascade,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.diagnostic_results enable row level security;
alter table public.lesson_progress enable row level security;
alter table public.attempts enable row level security;
alter table public.plan_items enable row level security;
alter table public.coach_sessions enable row level security;
alter table public.coach_messages enable row level security;

create policy "Users can read own profile" on public.profiles for select using (auth.uid() = id);
create policy "Users can update own profile" on public.profiles for update using (auth.uid() = id);
create policy "Users can read own diagnostics" on public.diagnostic_results for select using (auth.uid() = user_id);
create policy "Users can write own diagnostics" on public.diagnostic_results for insert with check (auth.uid() = user_id);
create policy "Users can manage own lesson progress" on public.lesson_progress for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can read own attempts" on public.attempts for select using (auth.uid() = user_id);
create policy "Users can write own attempts" on public.attempts for insert with check (auth.uid() = user_id);
create policy "Users can manage own plans" on public.plan_items for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can manage own coach sessions" on public.coach_sessions for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can manage own coach messages" on public.coach_messages for all using (
  exists (select 1 from public.coach_sessions s where s.id = session_id and s.user_id = auth.uid())
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, name) values (new.id, coalesce(new.raw_user_meta_data->>'name', ''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();
